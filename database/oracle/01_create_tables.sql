-- 1. USERS Table
CREATE TABLE users (
    user_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR2(100) NOT NULL UNIQUE,
    password    VARCHAR2(100) NOT NULL,
    email       VARCHAR2(100) NOT NULL UNIQUE
);

-- 2. AGENT Table
CREATE TABLE agent (
    agent_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname   VARCHAR2(100) NOT NULL,
    lastname    VARCHAR2(100) NOT NULL,
    email       VARCHAR2(100) NOT NULL UNIQUE,
    phone       VARCHAR2(20),
    agency      VARCHAR2(100)
);

-- 3. OWNER Table
CREATE TABLE owner (
    owner_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname    VARCHAR2(100) NOT NULL,
    lastname     VARCHAR2(100) NOT NULL,
    email        VARCHAR2(100) NOT NULL UNIQUE,
    phone_number VARCHAR2(20),
    agent_id     NUMBER
);

-- 4. CLIENTS Table
CREATE TABLE clients (
    client_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname   VARCHAR2(100) NOT NULL,
    lastname    VARCHAR2(100) NOT NULL,
    email       VARCHAR2(100) NOT NULL UNIQUE,
    phone       VARCHAR2(20)
);

-- 5. PROPERTY Table
CREATE TABLE property (
    property_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_type VARCHAR2(50) NOT NULL,
    address       VARCHAR2(255) NOT NULL,
    county        VARCHAR2(100) NOT NULL,
    city          VARCHAR2(100) NOT NULL,
    price_ksh     NUMBER(14,2) NOT NULL,
    owner_id      NUMBER,
    agent_id      NUMBER,
    zipcode       VARCHAR2(20),
    size_m2       NUMBER(10,2),
    status        VARCHAR2(30) DEFAULT 'Available' NOT NULL
);

-- 6. TENANT Table
CREATE TABLE tenant (
    tenant_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname    VARCHAR2(100) NOT NULL,
    lastname     VARCHAR2(100) NOT NULL,
    email        VARCHAR2(100) NOT NULL UNIQUE,
    phone_number VARCHAR2(20),
    lease_start  DATE,
    lease_end    DATE,
    property_id  NUMBER,
    agent_id     NUMBER
);

-- 7. LEASE Table
CREATE TABLE lease (
    lease_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lease_start  DATE NOT NULL,
    lease_end    DATE NOT NULL,
    monthly_rent NUMBER(12,2) NOT NULL,
    property_id  NUMBER NOT NULL,
    tenant_id    NUMBER NOT NULL,
    status       VARCHAR2(30) DEFAULT 'Active' NOT NULL
);

-- 8. PAYMENT Table
CREATE TABLE payment (
    payment_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_date   DATE DEFAULT SYSDATE NOT NULL,
    amount_paid    NUMBER(12,2) NOT NULL,
    payment_method VARCHAR2(50) NOT NULL,
    lease_id       NUMBER NOT NULL
);

-- 9. MAINTENANCE_REQUEST Table
CREATE TABLE maintenance_request (
    request_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_date DATE DEFAULT SYSDATE NOT NULL,
    description  VARCHAR2(500) NOT NULL,
    status       VARCHAR2(50) DEFAULT 'Open' NOT NULL,
    property_id  NUMBER,
    tenant_id    NUMBER
);

-- 10. TRANSACTIONS Table (Sales / Deeds)
CREATE TABLE transactions (
    transaction_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id      NUMBER NOT NULL,
    client_id        NUMBER NOT NULL,
    agent_id         NUMBER NOT NULL,
    transaction_date DATE DEFAULT SYSDATE NOT NULL,
    amount           NUMBER(14,2) NOT NULL,
    status           VARCHAR2(50) DEFAULT 'Completed' NOT NULL
);

-- 11. CLIENT_INTERACTIONS Table
CREATE TABLE client_interactions (
    interaction_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id        NUMBER NOT NULL,
    interaction_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    interaction_type VARCHAR2(50) NOT NULL,
    notes            VARCHAR2(2000)
);

-- 12. AUTOMATED_COMMUNICATIONS Table
CREATE TABLE automated_communications (
    communication_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id          NUMBER NOT NULL,
    communication_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    message            VARCHAR2(2000) NOT NULL,
    status             VARCHAR2(50) DEFAULT 'Sent' NOT NULL
);

-- 13. SECURITY_AUDIT Table
CREATE TABLE security_audit (
    audit_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_timestamp TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    user_id         NUMBER,
    action          VARCHAR2(255) NOT NULL,
    details         VARCHAR2(2000)
);

-- 14. REPORTS Table
CREATE TABLE reports (
    report_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generated_on TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    report_type  VARCHAR2(100) NOT NULL,
    report_data  CLOB CHECK (report_data IS JSON)
);

